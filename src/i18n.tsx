type I18nValue = {
  language: Language
  setLanguage: (language: Language) => void
  t: (message: string, values?: Record<string, string | number>) => string
  formatDate: (value: string | Date, options?: Intl.DateTimeFormatOptions) => string
  storageError: string
}

const I18nContext = createContext<I18nValue | null>(null)

export function readLanguage(storage: Pick<Storage, 'getItem'>): Language {
  const stored = storage.getItem(languageStorageKey)
  return stored === 'en' || stored === 'kk' || stored === 'ru' ? stored : 'ru'
}

export function storeLanguage(language: Language, storage: Pick<Storage, 'setItem'>) {
  storage.setItem(languageStorageKey, language)
}

const localeCodes: Record<Language, string> = { ru: 'ru-RU', en: 'en-US', kk: 'kk-KZ' }

export function translate(message: string, language: Language, values?: Record<string, string | number>) {
  let translated = translations[language][message] ?? message
  if (values) translated = translated.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`))
  return translated
}

export function formatDateForLanguage(value: string | Date, language: Language, options: Intl.DateTimeFormatOptions = { year: 'numeric', month: 'short', day: 'numeric' }) {
  const date = value instanceof Date ? value : new Date(/^\d{4}-\d{2}-\d{2}$/.test(value) ? `${value}T12:00:00` : value)
  if (!Number.isFinite(date.getTime())) return '—'
  return new Intl.DateTimeFormat(localeCodes[language], options).format(date)
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      return readLanguage(window.localStorage)
    } catch {
      return 'ru'
    }
  })
  const [storageError, setStorageError] = useState('')

  const setLanguage = (next: Language) => {
    setLanguageState(next)
    try {
      storeLanguage(next, window.localStorage)
      setStorageError('')
    } catch (error) {
      setStorageError('Could not save language preference. Browser storage is unavailable.')
    }
  }

  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (message, values) => translate(message, language, values),
    formatDate: (value, options) => formatDateForLanguage(value, language, options),
    storageError,
  }), [language, storageError])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used within I18nProvider.')
  return context
}

export function LanguagePicker({ className = '' }: { className?: string }) {
  const { language, setLanguage, t, storageError } = useI18n()
  return <label className={className}>
    {t('Language')}
    <select aria-label={t('Select language')} value={language} onChange={(event) => setLanguage(event.target.value as Language)}>
      <option value="ru">{t('Russian')}</option>
      <option value="en">{t('English')}</option>
      <option value="kk">{t('Kazakh')}</option>
    </select>
    {storageError && <small role="alert">{t(storageError)}</small>}
  </label>
}
